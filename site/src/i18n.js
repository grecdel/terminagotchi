export const COOKIE_LANGUE = "lang";

const valide = (x) => (typeof x === "string" && LANGUES.includes(x.trim().toLowerCase()) ? x.trim().toLowerCase() : null);

function depuisCookie(entete) {
  const m = String(entete || "").match(/(?:^|;\s*)lang=([^;]*)/);
  return m ? valide(decodeURIComponent(m[1])) : null;
}

/** Lit Accept-Language (« de-CH,de;q=0.9,en;q=0.8 ») et rend la meilleure langue connue. */
export function depuisAcceptLanguage(entete) {
  const items = String(entete || "").split(",").map((morceau, i) => {
    const [tag, ...params] = morceau.trim().split(";");
    let q = 1;
    for (const p of params) {
      const m = p.trim().match(/^q=([0-9.]+)$/i);
      if (m) q = Number(m[1]);
    }
    return { code: tag.trim().toLowerCase().split("-")[0], q: Number.isFinite(q) ? q : 0, i };
  }).filter((x) => x.code && x.q > 0).sort((a, b) => b.q - a.q || a.i - b.i);
  for (const x of items) if (LANGUES.includes(x.code)) return x.code;
  return null;
}

/**
 * Choisit la langue d'une requête.
 * @returns {{ lang: string, demandee: string|null }} `demandee` = la langue passée par ?lang= (à mémoriser en cookie).
 */
export function choisirLangue(requete, url) {
  const demandee = valide(url.searchParams.get("lang"));
  const lang = demandee
    || depuisCookie(requete.headers.get("cookie"))
    || depuisAcceptLanguage(requete.headers.get("accept-language"))
    || LANGUE_DEFAUT;
  return { lang, demandee };
}

export function cookieLangue(lang) {
  return `${COOKIE_LANGUE}=${lang}; Path=/; Max-Age=31536000; SameSite=Lax`;
}

const pl = (n, un, plusieurs) => (n > 1 ? plusieurs : un);
const plEn = (n, un, plusieurs) => (n === 1 ? un : plusieurs);
/** Pluriel russe : 1 / 2-4 / 5+ (21 → un, 22 → few, 11-14 → many). */
const plRu = (n, un, peu, beaucoup) => {
  const a = n % 10;
  const b = n % 100;
  return a === 1 && b !== 11 ? un : a >= 2 && a <= 4 && (b < 12 || b > 14) ? peu : beaucoup;
};

