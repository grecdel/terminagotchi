/** Fusion profonde : ce qui manque dans une langue est pris en français. */
function fusion(base, sur) {
  if (!sur) return base;
  const r = { ...base };
  for (const [k, v] of Object.entries(sur)) {
    r[k] = v && typeof v === "object" && !Array.isArray(v) && base[k] && typeof base[k] === "object" && !Array.isArray(base[k])
      ? fusion(base[k], v) : v;
  }
  return r;
}

const CACHE = {};
/** Les textes d'une langue (complétés par le français). */
export function textes(lang) {
  const l = LANGUES.includes(lang) ? lang : LANGUE_DEFAUT;
  return (CACHE[l] ??= fusion(fr, l === "fr" ? null : DICTIONNAIRES[l]));
}

/** Traduit une valeur de donnée (rareté, famille, habitat…) ; si elle est inconnue, on garde le français. */
export function libelle(table, cle) {
  return table?.[cle] ?? cle;
}
