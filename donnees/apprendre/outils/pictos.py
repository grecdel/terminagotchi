ORDRE = ["pwd", "ls", "cd", "mkdir", "touch", "cp", "mv", "rm", "cat", "less", "head", "grep", "find", "wc", "sort",
         "tree", "rev", "whoami", "date", "chmod"]


def verifier():
    assert ORDRE == list(P) or sorted(ORDRE) == sorted(P), sorted(set(ORDRE) ^ set(P))
    for c, rows in P.items():
        assert len(rows) == 16, (c, len(rows))
        for i, r in enumerate(rows):
            assert len(r) == 16, (c, i, r, len(r))
            for ch in r:
                assert ch == "." or ch in PALETTE, (c, ch)


def ecrire(racine):
    verifier()
    for f in ("pc/tg/apprendre.json", "app/src/main/assets/apprendre.json"):
        p = Path(racine) / f
        d = json.loads(p.read_text(encoding="utf-8"))
        d["pictos"] = {"palette": PALETTE, "ordre": ORDRE, "images": {c: P[c] for c in ORDRE}}
        p.write_text(json.dumps(d, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    ecrire(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[3])
    print("20 images écrites")
